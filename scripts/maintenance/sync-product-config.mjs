import { readFile, writeFile, mkdir, rename } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = dirname(
  dirname(dirname(fileURLToPath(import.meta.url))),
);
const productConfigPath = join(repositoryRoot, "apps/product.config.json");
const packageRoot = join(repositoryRoot, "packages/product-config");
const check = process.argv.includes("--check");
const product = JSON.parse(await readFile(productConfigPath, "utf8"));
for (const key of [
  "displayName",
  "namespace",
  "appDataDirName",
  "envPrefix",
  "bundleIdentifier",
])
  if (typeof product[key] !== "string" || !product[key].trim())
    throw new Error(`Invalid product config: ${key}`);
if (!/^[a-z][a-z0-9]*$/.test(product.namespace))
  throw new Error("Invalid product namespace");
if (!/^[A-Z][A-Z0-9_]*$/.test(product.envPrefix))
  throw new Error("Invalid product envPrefix");
for (const key of ["appDataDirName", "defaultWorkspaceDirName"])
  if (
    !product[key] ||
    /[/\\]/.test(product[key]) ||
    [".", ".."].includes(product[key])
  )
    throw new Error(`Invalid ${key}`);

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const escapeHtml = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

await sync("packages/product-config/product.config.json", json(product));
const declaration = (value) => {
  if (Array.isArray(value))
    return `readonly [${value.map(declaration).join(", ")}]`;
  if (value && typeof value === "object")
    return `{\n${Object.entries(value)
      .map(
        ([key, item]) =>
          `  readonly ${JSON.stringify(key)}: ${declaration(item)};`,
      )
      .join("\n")}\n}`;
  return JSON.stringify(value);
};
const { PRODUCT_KEYS: keys } =
  await import("../../packages/product-config/index.js");
await sync(
  "packages/product-config/index.d.ts",
  `// Generated by pnpm sync-product-config. Do not edit.\nexport declare const PRODUCT_CONFIG: ${declaration(product)};\nexport declare const APP_DISPLAY_NAME: typeof PRODUCT_CONFIG.displayName;\nexport declare const APP_DATA_DIR_NAME: typeof PRODUCT_CONFIG.appDataDirName;\nexport declare const PRODUCT_NAMESPACE: typeof PRODUCT_CONFIG.namespace;\nexport declare const DEFAULT_WORKSPACE_DIR_NAME: typeof PRODUCT_CONFIG.defaultWorkspaceDirName;\nexport type ProductId<Suffix extends string = ""> = \`\${typeof PRODUCT_NAMESPACE}\${Suffix}\`;\nexport declare function productId<Suffix extends string = "">(suffix?: Suffix): ProductId<Suffix>;\nexport declare function productDataName<Suffix extends string = "">(suffix?: Suffix): \`\${typeof APP_DATA_DIR_NAME}\${Suffix}\`;\nexport declare function envName<Suffix extends string>(suffix: Suffix): \`\${typeof PRODUCT_CONFIG.envPrefix}_\${Suffix}\`;\nexport declare function appStorageKey(name: string): string;\nexport declare const PRODUCT_KEYS: ${declaration(keys)};\n`,
);

const indexPath = "apps/client/index.html";
const index = await readFile(join(repositoryRoot, indexPath), "utf8");
const dotIndex = product.displayName.lastIndexOf("i");
const brand =
  dotIndex < 0
    ? escapeHtml(product.displayName)
    : `<span aria-hidden="true">${escapeHtml(product.displayName.slice(0, dotIndex))}</span><span class="startup-welcome__brand-i" aria-hidden="true"><span class="startup-welcome__brand-i-letter">i</span><img class="startup-welcome__brand-i-dot" src="${escapeHtml(product.assets.brandMark)}" alt="" width="256" height="256" decoding="sync" /></span><span aria-hidden="true">${escapeHtml(product.displayName.slice(dotIndex + 1))}</span>`;
