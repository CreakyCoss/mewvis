// Only static product definitions are listed here; package/import references
// remain ordinary source references. Templates make synchronization repeatable
// even after an interrupted build or when switching back to an older brand.
const definitions = JSON.parse(
  await readFile(
    join(repositoryRoot, "scripts/maintenance/product-definitions.json"),
    "utf8",
  ),
);
const expand = (value) =>
  typeof value === "string"
    ? value.replace(/\{([\w.]+)\}/g, (_, key) => {
        const result = key
          .split(".")
          .reduce((current, part) => current?.[part], product);
        if (typeof result !== "string")
          throw new Error(`Unknown product field: ${key}`);
        return result;
      })
    : value;
const keyFor = (object, template) => {
  const target = expand(template);
  if (Object.hasOwn(object, target)) return target;
  if (!template.includes("{"))
    throw new Error(`Missing metadata key: ${target}`);
  const pattern = new RegExp(
    "^" +
      template
        .split(/(\{[\w.]+\})/)
        .map((part) =>
          part.startsWith("{")
            ? ".+?"
            : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"),
        )
        .join("") +
      "$",
  );
  const candidates = Object.keys(object).filter(
    (key) =>
      pattern.test(key) && (template !== "{namespace}" || object[key]?.app),
  );
  if (candidates.length !== 1)
    throw new Error(`Ambiguous metadata key: ${template}`);
  return candidates[0];
};
const parentAt = (object, path) =>
  path.reduce(
    (current, part) =>
      current[typeof part === "number" ? part : keyFor(current, part)],
    object,
  );
let protocolChanged = false;
for (const [file, definition] of Object.entries(definitions)) {
  const source = await readFile(join(repositoryRoot, file), "utf8");
  const data = JSON.parse(source);
  for (const [path, template] of definition.keys) {
    const parent = parentAt(data, path);
    const key = keyFor(parent, template);
    const target = expand(template);
    if (key !== target) {
      parent[target] = parent[key];
      delete parent[key];
    }
  }
  for (const [path, template] of definition.values) {
    const parent = parentAt(data, path.slice(0, -1));
    parent[
      typeof path.at(-1) === "number"
        ? path.at(-1)
        : keyFor(parent, path.at(-1))
    ] = expand(template);
  }
  if (JSON.stringify(data) !== JSON.stringify(JSON.parse(source))) {
    await sync(file, json(data));
    protocolChanged ||= file.startsWith("apps/agent-runtime/protocol/");
  }
}
// Public generated type names stay fixed; regenerate their enum values whenever
// configuration changes the protocol definitions before consumers are compiled.
if (protocolChanged && !check) {
  const generator = join(
    repositoryRoot,
    "apps/agent-runtime/protocol/scripts/generate-bindings.mjs",
  );
  if (
    await readFile(generator, "utf8")
      .then(() => true)
      .catch((error) => {
        if (error.code !== "ENOENT") throw error;
        return false;
      })
  ) {
    const { execFileSync } = await import("node:child_process");
    execFileSync(
      "pnpm",
      ["--filter", "@mewvis/agent-runtime", "generate:protocol"],
      { cwd: repositoryRoot, stdio: "inherit" },
    );
  }
}
console.log(`${check ? "Checked" : "Synced"} product config`);

async function sync(relative, next) {
  const target = join(repositoryRoot, relative);
  const current = await readFile(target, "utf8").catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (current === next) return;
  if (check)
    throw new Error(
      `Product config output is stale: ${relative}. Run pnpm sync-product-config.`,
    );
  await mkdir(dirname(target), { recursive: true });
  const temporary = `${target}.${process.pid}.tmp`;
  await writeFile(temporary, next, "utf8");
  await rename(temporary, target);
}
